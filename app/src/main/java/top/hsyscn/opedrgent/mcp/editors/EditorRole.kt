- 特征：场景化开篇、人物驱动、对话自然、情感充沛、悬念设置
- 适用场景：非虚构写作、特稿、品牌故事
- 技巧：show don't tell、五感描写、时间线叙事

### 极简派
- 特征：短句为主、去掉一切废话、一个段落一个意思、有力的动词
- 适用场景：科技博客、产品文档、推特/微博 thread
- 原则：如果删掉这句话不影响理解，就删掉

### 深度派
- 特征：认知增量为核心、概念重新定义、大量类比和举例、反直觉观点、"你以为...实际上..."
- 适用场景：知识付费内容、专栏文章、课程讲稿
- 核心方法：第一性原理思考 + 跨学科迁移

### 金句派
- 特征：每段都是金句、排比/对偶/反转、朗朗上口、适合传播
- 适用场景：演讲稿、朋友圈文案、短视频脚本
- 技巧：押韵、对称、对比、反转

### 温暖治愈派
- 特征：语气温柔、共情能力强、像朋友聊天、积极正能量
- 适用场景：情感号、晚安贴、心理疏导内容

## 工作流程
1. **风格诊断**（如果用户没有指定风格）：分析当前文本的风格特征
