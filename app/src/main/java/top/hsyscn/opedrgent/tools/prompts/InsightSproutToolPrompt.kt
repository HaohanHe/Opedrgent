package top.hsyscn.opedrgent.tools.prompts

object InsightSproutToolPrompt {
    const val DESCRIPTION = "知识发芽（Insight Sprout）：对输入文本进行 4 阶段深度多维度分析，发芽衍生出结构化的洞察报告。" +
        "支持种子提取、跨领域关联、震惊瞬间洞察生成、金句回响四个阶段。"

    const val USAGE_GUIDELINES = """
## insight_sprout 工具使用规范

### 工具概述
知识发芽是一种深度文本分析方法，通过 4 个阶段对输入文本进行多维度发散思考：
1. **种子提取** — 从文本中识别核心概念和关键论点
2. **跨领域关联** — 将种子概念映射到不同知识领域，建立类比和联结
3. **震惊瞬间洞察** — 基于前两阶段生成反直觉的深层洞察
4. **金句回响** — 匹配经典引用并延展思考

---

### 参数说明

| 参数 | 类型 | 必填 | 默认值 | 说明 |
|------|------|------|--------|------|
| `text` | string | ✅ 是 | — | 待分析的原始文本内容（10 ~ 50000 字符） |
| `length` | string | ❌ 否 | `"medium"` | 输出长度控制：`"short"`(~500字) / `"medium"`(~1000字) / `"long"`(~2000字) |
| `domains` | string | ❌ 否 | null | 偏好分析领域，逗号分隔，如 `"心理学,经济学,历史,哲学"` |
| `use_context` | string | ❌ 否 | `"true"` | 是否注入用户上下文辅助分析：`"true"` / `"false"` |

#### length 参数详解
- **`short`**: 精简模式，约 500 字输出，适合快速浏览核心洞察
- **`medium`** (默认): 标准模式，约 1000 字输出，平衡了深度与可读性
- **`long`**: 完整模式，约 2000 字输出，包含详尽的分析和延展

#### domains 参数详解
不指定时引擎自动判断最相关的分析维度。支持的典型领域：
- **人文类**: 心理学、哲学、历史学、文学、社会学、人类学、语言学
- **科学类**: 物理学、生物学、计算机科学、数学、神经科学、认知科学
- **社科类**: 经济学、政治学、法学、教育学、传播学、管理学
- **艺术类**: 艺术理论、音乐学、建筑学、设计学、电影研究

示例: `"心理学,哲学,物理学"`

#### use_context 参数详解
- **`"true"`** (默认): 引擎会结合用户的历史对话上下文进行个性化分析
- **`"false"`**: 纯基于输入文本进行分析，不引入外部上下文

---

### 触发场景与调用时机

#### 显式触发（用户直接请求）
用户明确要求发芽时立即调用：

| 用户表述 | 示例 |
|---------|------|
| 直接请求发芽 | 「帮我对这段话发芽」「来个发芽报告」 |
| 要求深化分析 | 「帮我深化这个观点」「从多个角度分析一下」 |
| 请求灵感激发 | 「给我一些灵感」「这个想法能怎么延伸？」 |
| 询问深层含义 | 「这个观点有什么深层含义？」「背后隐藏着什么？」 |
| 跨领域联想 | 「从经济学的角度看这个问题」「这让我想到了什么？」 |

#### 隐式触发（LLM 判断值得深化）
当以下条件满足时，可以主动调用 insight_sprout：

1. **用户分享了一段有深度的笔记/文章/想法**（>100 字且包含明确观点）
2. **用户在讨论中提出了一个值得展开的核心论点**
3. **用户的提问涉及「为什么」「意味着什么」「本质是什么」等深层追问**
4. **用户表达了困惑或想要更全面的理解**

> ⚠️ 注意：隐式触发时应先征得用户同意或以建议方式提出：「我注意到这段内容很有意思，要不要我用知识发芽工具帮你做一次深度分析？」

---

### 输入验证规则

| 条件 | 处理方式 |
|------|---------|
| text 为空或未提供 | 返回错误，提示 text 为必填参数 |
| text < 10 字符 | 返回错误，提示文本过短 |
| text > 50000 字符 | 返回错误，提示文本过长 |
| text > 2000 字符 | 自动截取关键段落（按段落重要性评分排序） |

---

### 输出格式

返回结构化的 Markdown 报告，格式如下：

```
🌱 **知识发芽完成**

已完成 N/4 阶段的处理，以下是您的发芽报告：

---
[Engine 生成的 Markdown 报告]
---

📊 **质量评分**: XX/100 (优秀/良好/一般/较差)
⏱️ **处理耗时**: X.Xs

💡 **后续建议**:
- 对某个领域感兴趣？可以指定 --domains="心理学,哲学" 深化分析
- 想要更长或更短的报告？调整 --length="long" 或 --length="short"
- 复制全文或点击「继续追问」深入探讨
```

#### 质量评分标准
| 分数区间 | 等级 | 含义 |
|---------|------|------|
| 85 - 100 | 🏆 优秀 | 种子丰富、联结多样、洞察深刻、金句贴切 |
| 70 - 84 | ✅ 良好 | 分析较为完整，有一定启发价值 |
| 50 - 69 | ⚠️ 一般 | 基础分析完成，但深度有限 |
| 0 - 49 | ❌ 较差 | 多数阶段失败，结果参考价值低 |

---

### 性能考量

- 发芽过程涉及 **4 次 LLM 顺序调用**，预计耗时 10s ~ 60s
- 对于长文本（>2000 字），会自动截取关键段落以控制处理时间
- 相同文本 + 相同参数的结果会被缓存（最多 8 条），重复请求秒级返回
- 若某阶段超时或失败，剩余阶段仍会继续执行，最终报告中标注完成阶段数

---

### 最佳实践

1. **输入质量 > 输入数量**：一段 300 字的观点密集型文本比 3000字的流水账更适合发芽
2. **善用 domains 参数**：当用户有明确的学科偏好时指定，可显著提高分析的针对性
3. **长文本预处理**：对于长文，建议先提取核心段落再传入，而非全文灌入
4. **迭代式深化**：可以先 medium 快速看概貌，再对感兴趣的点用 long + specific domains 深化
5. **结合上下文**：保持 use_context=true 可以让发芽结果更贴合当前对话情境

### 限制与注意事项
- 单次输入文本上限 50000 字符（过长文本会自动截取）
- 发芽质量高度依赖输入文本的信息密度（观点、论述、案例等）
- 极短文本（<50字）或纯数据/代码片段可能产生有限的分析结果
- LLM 调用可能因网络问题导致个别阶段失败，工具会降级处理
- 缓存基于文本内容和参数组合的哈希值，完全相同的请求不会重复计算
"""

    fun getToolPrompt(): String = "$DESCRIPTION\n$USAGE_GUIDELINES"
}
