package top.hsyscn.opedrgent.ui.theme

import androidx.compose.ui.unit.dp

/**
 * 统一间距 token。
 *
 * 使用规则：
 * - xxs: 图标与文字极紧凑间距、行内元素
 * - xs: 小图标间距、紧凑列表项
 * - sm: 卡片内小间距、按钮内部
 * - md: 卡片内边距、列表项间距
 * - lg: 屏幕卡片间距、Section 间距
 * - xl: 大模块间距
 * - xxl: 页面级间距
 */
object SpacingTokens {
    val none = 0.dp
    val xxs = 2.dp
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
}
